#!/usr/bin/env node
/**
 * Regenerates src/lib/player-images.generated.ts from what is actually in
 * public/teams.
 *
 * Run this after adding or removing a player photograph:
 *
 *   npm run build:player-images
 *
 * Why a generated manifest instead of just pointing an <img> at the path and
 * letting it 404: a missing photograph is the normal case here, not an error.
 * An optimistic <img> would issue one failing request per player — 384 of them
 * on a full sweep of the 48 team pages — and would flash a broken-image glyph
 * before the fallback swapped in. The manifest lets the component render the
 * monogram directly and never request a file that is not there.
 *
 * Mirrors scripts/build-flags.mjs, which does the same job for the 48 bundled
 * flag SVGs.
 */

import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = join(HERE, "..");
const TEAMS_DIR = join(FRONTEND, "public", "teams");
const OUT_FILE = join(FRONTEND, "src", "lib", "player-images.generated.ts");

/** Only raster formats a browser can decode. .webp is the documented default. */
const ALLOWED = new Set([".webp", ".png", ".jpg", ".jpeg", ".avif"]);

const NON_COMPOSING = {
  ø: "o",
  đ: "d",
  ð: "d",
  þ: "th",
  ł: "l",
  ß: "ss",
  æ: "ae",
  œ: "oe",
};

/**
 * MUST stay identical to `slugify` in src/lib/player-images.ts.
 * scripts/audit-player-images.mjs asserts the two agree.
 */
export function slugify(value) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[øđðþłßæœ]/g, (c) => NON_COMPOSING[c] ?? c)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function collect() {
  if (!existsSync(TEAMS_DIR)) return { keys: [], skipped: [] };

  const keys = [];
  const skipped = [];

  for (const teamEntry of readdirSync(TEAMS_DIR).sort()) {
    const teamPath = join(TEAMS_DIR, teamEntry);
    if (!statSync(teamPath).isDirectory()) continue;

    const teamSlug = slugify(teamEntry);
    if (teamSlug !== teamEntry) {
      skipped.push(`${teamEntry}/ (directory name is not a slug; expected "${teamSlug}")`);
      continue;
    }

    for (const file of readdirSync(teamPath).sort()) {
      const ext = extname(file).toLowerCase();
      if (!ALLOWED.has(ext)) continue;

      const playerSlug = basename(file, extname(file));
      if (slugify(playerSlug) !== playerSlug) {
        skipped.push(`${teamEntry}/${file} (filename is not a slug; expected "${slugify(playerSlug)}${ext}")`);
        continue;
      }
      keys.push(`${teamSlug}/${playerSlug}`);
    }
  }

  return { keys: [...new Set(keys)].sort(), skipped };
}

const { keys, skipped } = collect();

const body =
  keys.length === 0
    ? "  // No player photographs are bundled yet. Drop files into\n" +
      "  // public/teams/<team-slug>/<player-slug>.webp and re-run\n" +
      "  // `npm run build:player-images` to populate this list.\n"
    : keys.map((k) => `  ${JSON.stringify(k)},`).join("\n") + "\n";

mkdirSync(dirname(OUT_FILE), { recursive: true });

writeFileSync(
  OUT_FILE,
  `// AUTO-GENERATED by scripts/build-player-images.mjs — do not edit by hand.
//
// One key per photograph present in public/teams, as "<team-slug>/<player-slug>".
// Re-run \`npm run build:player-images\` after adding or removing an image.
//
// Every entry resolves to a same-origin file under /teams. Nothing in this file
// may ever be an absolute or external URL — that is what keeps player imagery at
// zero third-party requests.

export const PLAYER_IMAGE_KEYS: ReadonlySet<string> = new Set([
${body}]);

/** Count of bundled player photographs. Reported by the image audit. */
export const PLAYER_IMAGE_COUNT = ${keys.length};
`,
  "utf8"
);

console.log(`build-player-images: ${keys.length} photograph(s) indexed from public/teams`);
for (const s of skipped) console.warn(`  skipped: ${s}`);
